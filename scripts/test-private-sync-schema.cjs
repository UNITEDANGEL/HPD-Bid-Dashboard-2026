const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { DatabaseSync } = require('node:sqlite');
const db = new DatabaseSync(':memory:');
db.exec('PRAGMA foreign_keys = ON');
const migration = fs.readFileSync(path.join(__dirname, '../migrations/private-sync/0001_field_records.sql'), 'utf8');
db.exec(migration);
db.exec(migration);
const owner = 'synthetic@example.test';
const add = db.prepare('INSERT INTO field_records VALUES (?, ?, ?, ?, ?)');
add.run(owner, 'TEST1', 1, '{"note":"keep"}', '2026-09-28T12:00:00Z');
assert.throws(() => add.run(owner, 'TEST2', 1, '[]', 'now'));
assert.throws(() => add.run(owner, 'TEST2', 0, '{}', 'now'));
const update = db.prepare('UPDATE field_records SET payload = ?, revision = revision + 1 WHERE owner_email = ? AND job_id = ? AND revision = ?');
assert.equal(update.run('{"note":"new"}', owner, 'TEST1', 1).changes, 1);
assert.equal(update.run('{"note":"stale"}', owner, 'TEST1', 1).changes, 0);
assert.equal(update.run('{}', 'other@example.test', 'TEST1', 2).changes, 0);
const event = db.prepare('INSERT INTO field_events VALUES (?, ?, ?, ?, ?, ?)');
event.run(owner, 'op-1', 'TEST1', 2, '{}', 'now');
assert.throws(() => event.run(owner, 'op-1', 'TEST1', 3, '{}', 'now'));
assert.throws(() => event.run(owner, 'op-2', 'TEST1', 2, '{}', 'now'));
assert.throws(() => event.run(owner, 'op-3', 'MISSING', 1, '{}', 'now'));
db.exec('BEGIN');
update.run('{"note":"rollback"}', owner, 'TEST1', 2);
db.exec('ROLLBACK');
assert.equal(JSON.parse(db.prepare('SELECT payload FROM field_records').get().payload).note, 'new');
db.close();
console.log('PASS: private schema, owner-scoped revision guards, duplicate operations, history references and rollback (synthetic in-memory data only)');
