import { chromium } from "playwright";
import { routePrivate } from "./private-route-for-tests.mjs";
const out = process.argv[2];
const b = await chromium.launch();
const c = await b.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, serviceWorkers: "block" });
await routePrivate(c);
await c.route(/hpd-status-worker\.[^/]+\.workers\.dev/, (r) => r.fulfill({ json: { ok: true, overrides: {}, accepted: [] } }));
const page = await c.newPage();
const errors = []; page.on("pageerror", (e) => errors.push(e.message));
await page.goto("http://localhost:3920/map/?view=all&map=1", { waitUntil: "load" });
await page.waitForFunction(() => document.querySelectorAll(".leaflet-marker-icon").length > 3, null, { timeout: 120000 });
for (const ok of await page.locator('[data-hpd-smoke="fc-hpd-ping-ok"]').all()) await ok.click().catch(() => {});
const shot = async (n) => { await page.waitForTimeout(1800); await page.screenshot({ path: `${out}/walk-${n}.png` }); };
await page.locator('[data-hpd-smoke="fc-notices-open"]').click();
await shot("1-notices-tap");
console.log("1 board open:", await page.locator('[data-hpd-smoke="fc-board"]').count(), "picks on board:", await page.locator('.fc-notice-chooser.is-on-board').count());
await page.locator('[data-hpd-smoke="fc-notice-pick-priority"]').click();
await shot("2-priority");
console.log("2 board:", await page.locator('[data-hpd-smoke="fc-board"]').count(), "tray rows:", await page.locator('[data-hpd-smoke="fc-notice-tray-row"]').count(), "glow pins:", await page.locator(".leaflet-marker-icon.is-glow").count());
await page.locator('[data-hpd-smoke="fc-notice-tray-show"]').first().click();
await shot("3-show-job");
await page.locator(".fc-job-sheet-close").click();
await shot("4-closed-job");
console.log("4 chooser:", await page.locator('[data-hpd-smoke="fc-notice-chooser"]').count(), "glow pins:", await page.locator(".leaflet-marker-icon.is-glow").count());
await page.locator('[data-hpd-smoke="fc-notice-pick-erp"]').count();
await page.locator('[data-hpd-smoke="fc-notice-change"]').click().catch(() => {});
await page.locator('[data-hpd-smoke="fc-notice-pick-erp"]').click();
await shot("5-lewis-erp");
console.log("5 tray:", await page.locator('[data-hpd-smoke="fc-notice-tray-row"]').count(), "glow:", await page.locator(".leaflet-marker-icon.is-glow").count());
console.log("errors", errors);
await b.close();
