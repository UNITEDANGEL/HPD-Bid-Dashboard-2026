import assert from "node:assert/strict";
import { readFileSync, writeFileSync, mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import ts from "typescript";
const src = readFileSync("lib/photo-pairs.ts", "utf8");
const file = join(mkdtempSync(join(tmpdir(), "pp-")), "m.mjs");
writeFileSync(file, ts.transpileModule(src, { compilerOptions: { module: "ES2020", target: "ES2020" } }).outputText);
const { pairPhotos } = await import(pathToFileURL(file).href);
const p = (kind, t, mediaType = "image") => ({ kind, mediaType, capturedAt: t, id: kind + t });
const r = pairPhotos([p("after", "2"), p("before", "2"), p("before", "1"), p("after", "1"), p("before", "3"), p("before", "9", "video")]);
assert.equal(r.length, 3);
assert.equal(r[0].before.id, "before1");
assert.equal(r[0].after.id, "after1");
assert.equal(r[2].before.id, "before3");
assert.equal(r[2].after, null);
assert.equal(pairPhotos([]).length, 0);
console.log("photo-pairs ok");
